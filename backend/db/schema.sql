CREATE VIEW public.learner_package_view AS
SELECT
  l.id AS learner_id,
  u.name AS learner_name,
  u.email,
  u.phone,
  u.dob,
  l.mentor_id,
  l.start_date,
  l.note,
  p.id AS purchase_id,
  p.status,
  p.created_at,
  p.renewed_at,
  p.changed_at,
  pkg.id AS package_id,
  pkg.name AS package_name,
  pkg.price,
  pkg.duration_days,
  p.expired_at,
  p.expiry_date,
  p.extra_days,
  pkg.original_price
FROM public.learners l
JOIN public.users u ON u.id = l.user_id
LEFT JOIN public.purchases p ON p.learner_id = l.id
LEFT JOIN public.packages pkg ON pkg.id = p.package_id;

