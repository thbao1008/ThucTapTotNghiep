CREATE TABLE public.mentor_learner_messages (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 mentor_id INTEGER NOT NULL REFERENCES public.mentors(id),
 learner_id INTEGER NOT NULL REFERENCES public.learners(id),
 sender_user_id INTEGER NOT NULL REFERENCES public.users(id),
 client_id UUID NOT NULL,
 body TEXT NOT NULL CHECK(length(body) BETWEEN 1 AND 3000),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(sender_user_id, client_id)
);
CREATE INDEX online_classes_start_idx ON public.online_classes(start_time, id);
CREATE INDEX online_class_request_mentor_idx ON public.online_class_requests(mentor_id, id DESC);
CREATE INDEX mentor_learner_messages_pair_idx ON public.mentor_learner_messages(mentor_id, learner_id, id DESC);
COMMIT;
